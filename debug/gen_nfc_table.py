#!/usr/bin/env python3
"""Generate iris_nfc_table.h from Python's unicodedata.

Usage: python3 debug/gen_nfc_table.py > iris_nfc_table.h (Python 3.12: Unicode 15)
"""
import sys
import unicodedata as ud


def rows(items, per_line):
    for i in range(0, len(items), per_line):
        print("    " + " ".join(items[i:i + per_line]))


entries, classes = [], []
for c in range(0x110000):
    d = ud.decomposition(chr(c))
    if d and not d.startswith("<"):
        parts = [int(x, 16) for x in d.split()]
        a, b = parts[0], parts[1] if len(parts) > 1 else 0
        composes = b and ud.normalize("NFC", chr(a) + chr(b)) == chr(c)
        assert not b or b >= 0x300
        entries.append("{0x%X,0x%X,0x%X,%d}," % (c, a, b, 1 if composes else 0))
    k = ud.combining(chr(c))
    if k:
        if classes and classes[-1][1] == c - 1 and classes[-1][2] == k:
            classes[-1][1] = c
        else:
            classes.append([c, c, k])

print("/* Generated by debug/gen_nfc_table.py from Unicode %s. Do not edit. */\n"
      % ud.unidata_version)
print("/* Canonical decompositions, sorted: code point, first, second (0 for a")
print(" * singleton), and whether first + second composes back to it. */")
print("static const struct { uint32_t cp, first, second; int composes; } nfc_decomp[] = {")
rows(entries, 4)
print("};\n")
print("/* Non-zero canonical combining classes, sorted: first, last, class. */")
print("static const struct { uint32_t first, last; int ccc; } nfc_class[] = {")
rows(["{0x%X,0x%X,%d}," % tuple(r) for r in classes], 5)
print("};")
sys.stdout.flush()
